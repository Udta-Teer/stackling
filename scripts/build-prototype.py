#!/usr/bin/env python3
"""
Generate the prototype's embedded course data from content/*.json.

The prototype is a standalone file:// page, so it can't fetch content at
runtime (CORS). The content therefore has to be embedded. Hand-mirroring it
was the source of an entire bug class (source/embed drift), so this script
owns that region instead.

It replaces ONLY the text between the two markers below, leaving everything
else in prototype/lesson.html untouched (styles, engine, renderers).

Emits, derived entirely from content/*.json:
    const UNIT1 = {...}; ... const UNITn = {...};
    const COURSE = [UNIT1, ...];
    const TIERLABEL = [...];   // from each unit's `tier` field

Usage:
    python3 scripts/build-prototype.py           # write
    python3 scripts/build-prototype.py --check   # exit 1 if regeneration would change the file
"""

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTENT_GLOB = os.path.join(ROOT, "content", "*.json")
PROTOTYPE = os.path.join(ROOT, "prototype", "lesson.html")

START = "/* === GENERATED BY scripts/build-prototype.py — DO NOT EDIT BY HAND === */"
END = "/* === END GENERATED === */"

TIER_LABEL = {
    0: "Foundations",
    1: "Storing Data",
    2: "Serving Scale",
    3: "Hard Truths",
    4: "Design Challenges",
    5: "Production Systems",
}

# The filename is an immutable authoring identifier, not the learning path.
# Reordering files would rename 44 sources and risks breaking references and
# persisted progress. Keep the canonical path here, keyed by stable unitId.
# Each tuple also names the learner-facing stage; this deliberately differs
# from some historical `tier` values after the 44-unit curriculum migration.
COURSE_ORDER = [
    ("how-internet-works", "Request Foundations"),
    ("client-server-http", "Request Foundations"),
    ("apis", "Request Foundations"),
    ("latency-vs-throughput", "Request Foundations"),
    ("where-state-lives", "Request Foundations"),
    ("checkpoint-foundations", "Request Foundations"),
    ("what-a-database-is", "Durable Data"),
    ("sql-vs-nosql", "Durable Data"),
    ("indexes", "Durable Data"),
    ("transactions-and-acid", "Durable Data"),
    ("replication", "Durable Data"),
    ("checkpoint-storing-data", "Durable Data"),
    ("scaling-vertical-vs-horizontal", "Serving Traffic"),
    ("load-balancing", "Serving Traffic"),
    ("caching", "Serving Traffic"),
    ("cdns", "Serving Traffic"),
    ("sharding", "Serving Traffic"),
    ("rate-limiting", "Serving Traffic"),
    ("message-queues", "Serving Traffic"),
    ("idempotency", "Serving Traffic"),
    ("checkpoint-serving-scale", "Serving Traffic"),
    ("observability", "Distributed Systems"),
    ("resilience-backpressure", "Distributed Systems"),
    ("consistency-models", "Distributed Systems"),
    ("cap-theorem", "Distributed Systems"),
    ("consensus", "Distributed Systems"),
    ("disaster-recovery", "Distributed Systems"),
    ("checkpoint-hard-truths", "Distributed Systems"),
    ("authentication-authorization", "Production Systems"),
    ("security-threat-modeling", "Production Systems"),
    ("service-discovery-configuration", "Production Systems"),
    ("schema-data-migrations", "Production Systems"),
    ("event-streams-processing", "Production Systems"),
    ("multi-region-architecture", "Production Systems"),
    ("architecture-evolution", "Production Systems"),
    ("checkpoint-design-challenges", "Production Systems"),
    ("design-url-shortener", "Design Studio"),
    ("design-rate-limiter", "Design Studio"),
    ("design-notification-platform", "Design Studio"),
    ("design-news-feed", "Design Studio"),
    ("design-chat-app", "Design Studio"),
    ("design-cloud-file-storage", "Design Studio"),
    ("design-video-streaming", "Design Studio"),
    ("design-ride-sharing", "Design Studio"),
]


# Fields the renderer actually reads. The builder copies ONLY these into the
# embed — so anything a content author adds outside this list silently never
# reaches the learner, with every gate green. That has now happened twice
# (`fieldTask`, then `subtitle`), so the allowlist is declared here and enforced
# against the content below rather than being an implicit detail of lesson().
LESSON_FIELDS = {"id", "title", "exercises", "fieldTask"}
UNIT_FIELDS = {"unitId", "tier", "title", "subtitle", "objectives", "lessons"}
# `tier` and `objectives` are read by the build/tracker, not shipped to the page.
UNIT_NOT_EMBEDDED = {"tier", "objectives"}


def unit_number(path):
    m = re.match(r"(\d+)", os.path.basename(path))
    return int(m.group(1)) if m else 0


def build_block():
    files = sorted(glob.glob(CONTENT_GLOB), key=unit_number)
    if not files:
        raise SystemExit("no content files found")

    loaded = []
    by_id = {}
    for f in files:
        d = json.load(open(f, encoding="utf-8"))
        uid = d.get("unitId")
        if not uid:
            raise SystemExit(f"{os.path.basename(f)}: missing unitId")
        if uid in by_id:
            raise SystemExit(f"duplicate unitId {uid!r}")
        loaded.append((f, d))
        by_id[uid] = (f, d)

    ordered_ids = [uid for uid, _ in COURSE_ORDER]
    missing = [uid for uid in ordered_ids if uid not in by_id]
    unplaced = sorted(set(by_id) - set(ordered_ids))
    if missing or unplaced or len(ordered_ids) != len(set(ordered_ids)):
        raise SystemExit(
            f"COURSE_ORDER mismatch: missing={missing}, unplaced={unplaced}, "
            f"duplicate_order_ids={len(ordered_ids) != len(set(ordered_ids))}"
        )

    lines = [START]
    names_by_id = {}

    # Definitions stay in file-number order so UNIT23 continues to mean source
    # file 23. Only COURSE below controls the learner's progression.
    for f, d in loaded:
        n = unit_number(f)
        tier = d.get("tier")
        if tier not in TIER_LABEL:
            raise SystemExit(f"{os.path.basename(f)}: unknown tier {tier!r}")

        var = f"UNIT{n}"
        names_by_id[d["unitId"]] = var

        # Strip fields the renderer doesn't read, so the embed stays lean.
        def lesson(l):
            out = {
                "id": l.get("id"),
                "title": l.get("title"),
                "exercises": l.get("exercises", []),
            }
            if l.get("fieldTask"):          # optional post-lesson side quest
                out["fieldTask"] = l["fieldTask"]
            return out

        # Fail loudly on a field nobody will ever see, instead of dropping it.
        stray_u = set(d) - UNIT_FIELDS
        if stray_u:
            raise SystemExit(
                f"{os.path.basename(f)}: unknown unit-level field(s) {sorted(stray_u)}. "
                f"The builder only embeds {sorted(UNIT_FIELDS - UNIT_NOT_EMBEDDED)}, so this "
                f"would never reach a learner. Add it to UNIT_FIELDS and to the embed if it should.")
        for l in d.get("lessons", []):
            stray_l = set(l) - LESSON_FIELDS
            if stray_l:
                raise SystemExit(
                    f"{os.path.basename(f)}: lesson {l.get('id')!r} has unknown field(s) "
                    f"{sorted(stray_l)}. lesson() would drop them silently.")

        unit = {
            "unitId": d.get("unitId"),
            "title": d.get("title"),
            # The subtitle is the only place a checkpoint says WHY it has no
            # teaching cards ("Mixing units 23-27..."). Dropping it made the
            # exemption look like a bug — the reader lands on a test with no
            # lesson and reasonably concludes the teaching is missing.
            "subtitle": d.get("subtitle"),
            "lessons": [lesson(l) for l in d.get("lessons", [])],
        }
        blob = json.dumps(unit, ensure_ascii=False, separators=(",", ":"))

        # json.dumps escapes neither `<` nor `/`, and this blob lands inside an
        # inline <script>. The HTML parser ends that script at the first literal
        # `</script>` REGARDLESS of JS string quoting — so one such sequence in a
        # `why` (plausible: units 2 and 14 teach HTTP and CDNs) truncates the
        # script, COURSE never gets defined, and the page renders zero units.
        # Both Python gates reported PASS while the app was dead.
        blob = blob.replace("</", "<\\/")

        # Same class, different fuse: the region markers below are found with a
        # non-greedy `.*?`, so a marker that ends up INSIDE the embed becomes the
        # new end-of-region on the next build. The generator then appends a second
        # copy of every unit — duplicate `const UNIT1` declarations, SyntaxError,
        # dead page — and `--check` reports "stale" forever, with the remedy it
        # prints doubling the damage each time it's followed.
        for marker in (START, END):
            if marker in blob:
                raise SystemExit(
                    f"{os.path.basename(f)}: content contains the generated-region "
                    f"marker {marker!r}. Embedding it would make the next build "
                    f"truncate at the wrong place and duplicate every unit."
                )

        lines.append(f"/* ---- {os.path.basename(f)} ---- */")
        lines.append(f"const {var} = " + blob + ";")

    names = [names_by_id[uid] for uid, _ in COURSE_ORDER]
    labels = [label for _, label in COURSE_ORDER]
    lines.append("")
    lines.append(f"const COURSE = [{', '.join(names)}];")
    lines.append(
        "const TIERLABEL = ["
        + ",".join(json.dumps(x, ensure_ascii=False) for x in labels)
        + "];"
    )
    lines.append(END)
    return "\n".join(lines), len(files)


def main():
    check = "--check" in sys.argv
    block, n_units = build_block()
    html = open(PROTOTYPE, encoding="utf-8").read()

    if START in html and END in html:
        new = re.sub(
            re.escape(START) + r".*?" + re.escape(END),
            lambda _: block,
            html,
            flags=re.S,
        )
    else:
        # First run: replace the legacy hand-maintained region, which runs from
        # the first content comment through the TIERLABEL line.
        pat = re.compile(
            r"/\* ---- content \(from content/01.*?^const TIERLABEL = \[.*?\];",
            re.S | re.M,
        )
        if not pat.search(html):
            raise SystemExit(
                "cannot find the content region to replace, and no markers present"
            )
        new = pat.sub(lambda _: block, html, count=1)

    if new == html:
        print(f"prototype already up to date ({n_units} units)")
        return 0

    if check:
        print(
            "FAIL: prototype embed is stale — run: python3 scripts/build-prototype.py",
            file=sys.stderr,
        )
        return 1

    open(PROTOTYPE, "w", encoding="utf-8").write(new)
    print(f"prototype regenerated from {n_units} content files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
